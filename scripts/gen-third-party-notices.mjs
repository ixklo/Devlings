#!/usr/bin/env node
// Regenerates THIRD_PARTY_NOTICES.md from two sources:
//   - Rust crates that compile into the Tauri backend (normal deps only,
//     via `cargo about`, configured by src-tauri/about.toml)
//   - npm packages that ship in the frontend bundle (production deps from
//     package-lock.json; @types/* packages are skipped since they're
//     type-only and emit no runtime code)
//
// Requires `cargo-about` on PATH (`cargo install cargo-about --locked
// --features cli`). Run with: npm run notices:generate
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function generateRustLicenseData() {
  const raw = execFileSync(
    "cargo",
    ["about", "generate", "--format", "json", "-m", "src-tauri/Cargo.toml"],
    { cwd: root, maxBuffer: 64 * 1024 * 1024 },
  );
  return JSON.parse(raw.toString("utf8"));
}

function rustSection(data) {
  const crateList = data.crates
    .map((c) => ({ name: c.package.name, version: c.package.version, license: c.license }))
    .sort((a, b) => (a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name)));

  const lines = [];
  lines.push("## Rust crates");
  lines.push("");
  lines.push(
    `Compiled into Perch's Tauri backend (\`src-tauri\`), ${crateList.length} normal (runtime) dependencies, generated with [cargo-about](https://github.com/EmbarkStudios/cargo-about) from \`src-tauri/about.toml\`:`,
  );
  lines.push("");
  for (const c of crateList) {
    lines.push(`- ${c.name} ${c.version} — ${c.license}`);
  }
  lines.push("");
  lines.push("### License texts");
  lines.push("");
  const sortedLicenses = [...data.licenses].sort((a, b) => a.name.localeCompare(b.name));
  for (const lic of sortedLicenses) {
    const usedBy = lic.used_by
      .map((u) => `${u.crate.name} ${u.crate.version}`)
      .sort()
      .join(", ");
    lines.push(`#### ${lic.name} (${lic.id})`);
    lines.push("");
    lines.push(`Used by: ${usedBy}`);
    lines.push("");
    lines.push("```text");
    lines.push(lic.text.trimEnd());
    lines.push("```");
    lines.push("");
  }
  return lines.join("\n");
}

function readNpmProdPackages() {
  const lock = JSON.parse(readFileSync(path.join(root, "package-lock.json"), "utf8"));
  return Object.entries(lock.packages)
    .filter(([key, value]) => key.startsWith("node_modules/") && !value.dev)
    .map(([key, value]) => ({
      key,
      dir: key.replace(/^node_modules\//, ""),
      name: value.name ?? key.split("node_modules/").pop(),
      version: value.version,
      license: value.license ?? (Array.isArray(value.licenses) ? value.licenses.join(" OR ") : "unknown"),
    }))
    .filter((p) => !p.name.startsWith("@types/"))
    .sort((a, b) => (a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name)));
}

function findLicenseFiles(pkgDir) {
  if (!existsSync(pkgDir)) return [];
  return readdirSync(pkgDir).filter((f) => /^licen[sc]e/i.test(f) || /^copying/i.test(f));
}

function npmSection(packages) {
  const lines = [];
  lines.push("## npm packages");
  lines.push("");
  lines.push(
    `Bundled into Perch's frontend by Vite, ${packages.length} production dependencies from \`package-lock.json\` (type-only \`@types/*\` packages are omitted; they contribute no runtime code):`,
  );
  lines.push("");
  for (const p of packages) {
    lines.push(`- ${p.name} ${p.version} — ${p.license}`);
  }
  lines.push("");
  lines.push("### License texts");
  lines.push("");
  for (const p of packages) {
    const pkgDir = path.join(root, "node_modules", p.dir);
    const files = findLicenseFiles(pkgDir);
    lines.push(`#### ${p.name} ${p.version} (${p.license})`);
    lines.push("");
    if (files.length === 0) {
      lines.push(
        `No license file shipped with this package. See https://www.npmjs.com/package/${p.name}/v/${p.version} for the ${p.license} license text.`,
      );
    } else {
      for (const f of files) {
        const text = readFileSync(path.join(pkgDir, f), "utf8").trimEnd();
        lines.push("```text");
        lines.push(text);
        lines.push("```");
      }
    }
    lines.push("");
  }
  return lines.join("\n");
}

const header = `# Third-party notices

Perch is free and open source under the MIT license (see \`LICENSE\`). It's
built with the third-party software listed below, generated by
\`scripts/gen-third-party-notices.mjs\` (run \`npm run notices:generate\`) from
the Rust and npm dependency graphs that actually ship in the installers —
build tools and test-only dependencies are excluded. Settings → About links
here.

## Pet file format

Perch's pet file format (an atlas image plus a \`pet.json\` describing it,
see the README's "Making your own pet" section) follows the Codex pet
contract from [openai/skills](https://github.com/openai/skills)'
\`hatch-pet\` skill, licensed Apache-2.0. No Codex code is included in
Perch; this is a format-compatibility note, not a dependency.

`;

function main() {
  console.log("Generating Rust license data with cargo-about (this can take a minute)...");
  const rustData = generateRustLicenseData();
  const npmPackages = readNpmProdPackages();

  const body = [header.trimEnd(), "", rustSection(rustData), npmSection(npmPackages)].join("\n\n");
  const outPath = path.join(root, "THIRD_PARTY_NOTICES.md");
  writeFileSync(outPath, `${body.trimEnd()}\n`);
  console.log(`Wrote ${outPath} (${rustData.crates.length} Rust crates, ${npmPackages.length} npm packages).`);
}

main();
